package com.smileprotocol.run;

/** Tipo de partida (README 6.1). */
public enum RunType {
    /** Un mini ascensor: un grupo de 2 a 6 jugadores y su propia secuencia de zonas. */
    MINI,
    /** El mega ascensor: todos los del evento en grupos de 4 o 5, misma secuencia para todos. */
    MEGA,
    /** El ascensor TUTORIAL: solo la planta de entrenamiento, sin monstruos ni sustos. */
    TUTORIAL
}
